-- Idempotent schema for the Wei 52-week-high pullback backtester.
-- All result tables are prefixed backtest_wei_.
-- Re-run safe unless drop_all_wei_tables_on_start is set to true.

CREATE EXTENSION IF NOT EXISTS timescaledb;

DO $$
BEGIN
    IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'market-data-account') THEN
        CREATE USER "market-data-account" WITH PASSWORD 'market-data-account-pw';
    END IF;
END
$$;

GRANT CONNECT ON DATABASE postgres TO "market-data-account";
GRANT USAGE ON SCHEMA public TO "market-data-account";
ALTER DEFAULT PRIVILEGES IN SCHEMA public
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO "market-data-account";
ALTER DEFAULT PRIVILEGES IN SCHEMA public
    GRANT USAGE, SELECT ON SEQUENCES TO "market-data-account";

\if :drop_all_wei_tables_on_start
DROP TABLE IF EXISTS backtest_wei_equity_daily CASCADE;
DROP TABLE IF EXISTS backtest_wei_trades CASCADE;
DROP TABLE IF EXISTS backtest_wei_runs CASCADE;
DROP TABLE IF EXISTS backtest_wei_signals_daily CASCADE;
\endif

CREATE TABLE IF NOT EXISTS backtest_wei_signals_daily (
    period_end_date             DATE NOT NULL,
    symbol                      TEXT NOT NULL,
    ibkr_industry               TEXT,
    ibkr_category               TEXT,
    close                       NUMERIC(15,4) NOT NULL,
    high                        NUMERIC(15,4) NOT NULL,
    volume                      NUMERIC(20,4) NOT NULL,
    alpaca_price_feed           TEXT,
    planned_entry_market_cap_usd NUMERIC(20,2) NOT NULL,
    planned_entry_market_cap_currency TEXT NOT NULL,
    market_cap_pass             BOOLEAN NOT NULL,
    revenue_ttm                 NUMERIC(20,2) NOT NULL,
    prev_revenue_ttm            NUMERIC(20,2) NOT NULL,
    revenue_yoy                 NUMERIC(18,6) NOT NULL,
    revenue_pass                BOOLEAN NOT NULL,
    rolling_52w_high            NUMERIC(15,4) NOT NULL,
    is_52w_high                 BOOLEAN NOT NULL,
    had_52w_high_last_10d       BOOLEAN NOT NULL,
    ema_fast                    NUMERIC(15,6) NOT NULL,
    ema_slow                    NUMERIC(15,6) NOT NULL,
    prev_ema_fast               NUMERIC(15,6) NOT NULL,
    prev_ema_slow               NUMERIC(15,6) NOT NULL,
    ema_cross_up                BOOLEAN NOT NULL,
    ema_already_above_on_52w_high BOOLEAN NOT NULL,
    ema_entry_pass              BOOLEAN NOT NULL,
    volume_sma50                NUMERIC(20,4) NOT NULL,
    volume_sma50_pass           BOOLEAN NOT NULL,
    volume_feed_pass            BOOLEAN NOT NULL,
    volume_pass                 BOOLEAN NOT NULL,
    ibkr_industry_breadth_pct   NUMERIC(8,4),
    ibkr_industry_breadth_on    BOOLEAN NOT NULL,
    ibkr_industry_breadth_pass  BOOLEAN NOT NULL,
    entry_signal                BOOLEAN NOT NULL,
    planned_entry_date          DATE NOT NULL,
    planned_entry_open          NUMERIC(15,4) NOT NULL,
    created_ts                  TIMESTAMPTZ NOT NULL DEFAULT now()
);

SELECT create_hypertable(
    'backtest_wei_signals_daily',
    'period_end_date',
    chunk_time_interval => INTERVAL '365 days',
    if_not_exists => TRUE
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_backtest_wei_signals_daily_symbol
    ON backtest_wei_signals_daily (period_end_date, symbol);

CREATE INDEX IF NOT EXISTS idx_backtest_wei_signals_daily_industry
    ON backtest_wei_signals_daily (period_end_date DESC, ibkr_industry, ibkr_category);

CREATE TABLE IF NOT EXISTS backtest_wei_runs (
    run_id                      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    run_ts                      TIMESTAMPTZ NOT NULL DEFAULT now(),
    run_label                   TEXT NOT NULL,
    start_date                  DATE NOT NULL,
    end_date                    DATE NOT NULL,
    warmup_calendar_days        INTEGER NOT NULL,
    high_lookback_days          INTEGER NOT NULL,
    high_recent_days            INTEGER NOT NULL,
    ema_fast_days               INTEGER NOT NULL,
    ema_slow_days               INTEGER NOT NULL,
    volume_sma_days             INTEGER NOT NULL,
    volume_filter_enable        BOOLEAN NOT NULL,
    ibkr_industry_breadth_filter_enable BOOLEAN NOT NULL,
    ibkr_industry_breadth_on_threshold NUMERIC(8,4) NOT NULL,
    ibkr_industry_breadth_off_threshold NUMERIC(8,4) NOT NULL,
    ibkr_industry_breadth_min_symbols INTEGER NOT NULL,
    position_size_usd           NUMERIC(18,2) NOT NULL,
    stop_loss_pct               NUMERIC(12,6) NOT NULL,

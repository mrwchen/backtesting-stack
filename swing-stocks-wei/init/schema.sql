    min_market_cap_usd          NUMERIC(20,2) NOT NULL,
    revenue_yoy_min             NUMERIC(12,6) NOT NULL,
    revenue_stale_trading_days  INTEGER NOT NULL,
    signal_count                INTEGER NOT NULL,
    trade_count                 INTEGER NOT NULL,
    final_equity                NUMERIC(18,2),
    total_pnl                   NUMERIC(18,2),
    total_return                NUMERIC(18,6),
    cagr                        NUMERIC(18,6),
    max_drawdown                NUMERIC(18,6),
    win_rate                    NUMERIC(18,6),
    profit_factor               NUMERIC(18,6),
    avg_r_multiple              NUMERIC(18,6),
    avg_holding_days            NUMERIC(18,6)

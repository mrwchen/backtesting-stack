    ADD COLUMN IF NOT EXISTS volume_sma50_pass BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS volume_feed_pass BOOLEAN NOT NULL DEFAULT FALSE;

ALTER TABLE backtest_wei_signals_daily
